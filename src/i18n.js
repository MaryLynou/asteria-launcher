const DICTS = { fr: FR, en: EN, es: ES };
const LANGS = [
  { code: 'fr', label: 'Français', flag: '🇫🇷' },
  { code: 'en', label: 'English', flag: '🇬🇧' },
  { code: 'es', label: 'Español', flag: '🇪🇸' },
];

/** Traduit une cle. `params.n` choisit automatiquement la forme singulier/pluriel. */
function translate(lang, key, params) {
  const dict = DICTS[lang] || FR;
  let realKey = key;
  if (params && typeof params.n === 'number' && (dict[key + '_one'] || FR[key + '_one'])) {
    realKey = key + (params.n === 1 ? '_one' : '_other');
  }
  const model = dict[realKey] !== undefined ? dict[realKey] : FR[realKey];
  if (model === undefined) return key; // cle manquante : visible plutot que silencieuse
  if (!params) return model;
  return model.replace(/\{(\w+)\}/g, (whole, nom) => (params[nom] !== undefined ? String(params[nom]) : whole));
}

const API = { DICTS, LANGS, translate };

if (typeof module !== 'undefined' && module.exports) module.exports = API;
if (typeof window !== 'undefined') window.ASTERIA_I18N = API;
